const { chromium } = require('../../frontend/node_modules/playwright-core')
const assert = require('node:assert/strict')
;(async()=>{
 const browser=await chromium.launch({executablePath:process.env.LOCALAPPDATA+'/ms-playwright/chromium-1232/chrome-win64/chrome.exe'})
 try {
 const page=await browser.newPage({viewport:{width:650,height:850}})
 page.setDefaultTimeout(6500)
 const errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 const root='http://127.0.0.1:5174/'
 const btn=name=>page.getByRole('button',{name,exact:true})
 await page.goto(root+'#/tasks')
 await btn('新建任务').waitFor()
 await page.evaluate(async()=>{
   const req=indexedDB.open('jxl-product');const db=await new Promise(ok=>{req.onsuccess=()=>ok(req.result)})
   const t=db.transaction('docs','readwrite'),store=t.objectStore('docs'),ws={workspace_id:'personal'},now=new Date()
   store.put({...ws,kind:'task',id:'talk',title:'示例宣讲会',status:'doing',note_ids:[],deadline:{precision:'none',value:null},current_action_id:null,created_at:now.toISOString()})
   store.put({...ws,kind:'action',id:'check',task_id:'talk',text:'核对地点',minutes:10,done:false,created_at:now.toISOString()})
   store.put({...ws,kind:'plan_item',id:'original',task_id:'talk',date:new Intl.DateTimeFormat('sv-SE',{timeZone:'Asia/Shanghai'}).format(now),state:'planned',action_text:'确认后的时间地点信息',planned_minutes:10,actual_minutes:null,focus_session_id:null,task_ref_state:'active',order:1})
   await new Promise(ok=>{t.oncomplete=ok});db.close()
 })
 const snapshot=()=>page.evaluate(async()=>{
   const req=indexedDB.open('jxl-product'),db=await new Promise(ok=>req.onsuccess=()=>ok(req.result))
   const q=db.transaction('docs').objectStore('docs').getAll(),all=await new Promise(ok=>q.onsuccess=()=>ok(q.result))
   db.close()
   return {plan:all.find(x=>x.id==='original'),sessions:all.filter(x=>x.kind==='focus_session'),plans:all.filter(x=>x.kind==='plan_item').length}
 })
 await page.goto(root+'#/today?plan=original');await page.reload()
 await btn('开始这项安排').click()
 await btn('返回安排').click()
 await btn('保存并暂停后离开').click()
 const dialog=page.getByRole('dialog',{name:'工作安排详情'})
 await dialog.waitFor()
 const paused=await snapshot()
 assert.equal(paused.plan.state,'planned')
 assert.equal(paused.sessions.length,1)
 assert.equal(paused.sessions[0].running,false)
 await dialog.getByRole('button',{name:'编辑',exact:true}).click()
 await page.getByLabel('预计分钟',{exact:true}).fill('15')
 await btn('保存修改').click();await dialog.waitFor()
 const updated=await snapshot(); assert.equal(updated.plan.planned_minutes,15); assert.deepEqual(updated.sessions,paused.sessions)
 await btn('回到工作').click();await btn('结束本次').click()
 await page.getByRole('radio',{name:/还需要继续/}).check()
 await btn('结束并保存').click()
 await dialog.waitFor()
 const ended=await snapshot()
 assert.equal(ended.plan.state,'partial');assert(ended.sessions[0].ended_at)
 await btn('关闭工作面板').click();await page.goto(root+'#/tasks')
 await btn('安排工作：示例宣讲会').click()
 const row=page.getByRole('listitem').filter({hasText:'确认后的时间地点信息'})
 await row.getByText('部分完成',{exact:true}).waitFor()
 await row.getByRole('button',{name:'修改安排'}).click()
 await page.getByLabel('预计分钟',{exact:true}).fill('20')
 await page.getByLabel('工作说明',{exact:true}).fill('核对最终地点')
 await btn('保存修改').click();await dialog.waitFor()
 const last=await snapshot()
 assert.deepEqual(last.plan,{...ended.plan,planned_minutes:20,action_text:'核对最终地点'})
 assert.equal(last.plans,1);assert.deepEqual(last.sessions,ended.sessions)
 assert.deepEqual(errors,[])
 console.log('通过：真实开始、返回并暂停、编辑不恢复计时、结束为部分完成、任务列表修改同一安排，保留完整会话与实际用时。')
 } finally {await browser.close()}
})().catch(e=>{console.error(e.message);process.exitCode=1})


