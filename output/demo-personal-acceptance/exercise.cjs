const assert = require('node:assert/strict')
const path = require('node:path')
const { chromium } = require('../../frontend/node_modules/playwright-core')
;(async () => {
  const browser = await chromium.launch({executablePath:process.env.LOCALAPPDATA + '/ms-playwright/chromium-1232/chrome-win64/chrome.exe',headless:true})
  try {
    const page = await browser.newPage({viewport:{width:1100,height:800}})
    const root = 'http://127.0.0.1:5174'
    const check = await page.request.post(root+'/api/analyze?fail=422',{data:{source_id:'route-check',kind:'text',text:'示例',captured_at:'2026-11-26T09:00:00+08:00'}})
    const code = (await check.json()).code
    assert.equal(code,'invalid_request','页面仍连接样例服务，或鉴权失败：'+code)
    const errors=[], posts=[]
    page.on('pageerror',e=>errors.push(e.message))
    page.on('request',r=>{if(r.method()==='POST') posts.push(r.url())})
    await page.goto(root+'/#/assistant')
    const spaces = page.getByLabel('切换工作区').filter({visible:true})
    await spaces.selectOption('demo')
    await page.getByRole('heading',{name:'读一张作业通知'}).waitFor()
    assert.equal(await page.locator('input[type=file]').count(),0)
    await page.locator('img').evaluate(img=>img.decode())
    for(const title of ['核对提交要求','把报告安排到三天','开始第一项行动']) {
      await page.getByRole('button',{name:'继续',exact:true}).click()
      await page.getByRole('heading',{name:title}).waitFor()
    }
    await page.getByRole('button',{name:'上一步'}).click()
    await page.setViewportSize({width:390,height:844})
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
    await page.getByRole('button',{name:'继续',exact:true}).click()
    await page.getByRole('button',{name:'重新演示'}).click()
    await page.getByRole('heading',{name:'读一张作业通知'}).waitFor()
    await page.goto(root+'/#/collect')
    await page.getByRole('link',{name:'查看操作演示'}).waitFor()
    assert.equal(await page.locator('input[type=file]').count(),0)
    await page.evaluate(()=>{const data=new DataTransfer();data.items.add(new File(['example'],'demo.png',{type:'image/png'}));document.querySelector('main').dispatchEvent(new ClipboardEvent('paste',{bubbles:true,clipboardData:data}));document.querySelector('main > div').dispatchEvent(new DragEvent('drop',{bubbles:true,dataTransfer:data}))})
    await page.getByText('课程通知收在助手的操作演示里。').waitFor()
    assert.equal(posts.length,0)
    await page.getByRole('link',{name:'查看操作演示'}).click()
    await spaces.selectOption('personal')
    await page.getByRole('button',{name:'上传截图'}).waitFor()
    const png=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=850;c.height=220;const ctx=c.getContext('2d');ctx.fillStyle='white';ctx.fillRect(0,0,850,220);ctx.fillStyle='black';ctx.font='26px sans-serif';ctx.fillText('课程作业通知（虚构测试）',20,55);ctx.fillText('12 月 10 日前提交一页实验总结。',20,110);ctx.fillText('先整理两组实验结果，再撰写总结。',20,170);return c.toDataURL('image/png').split(',')[1]})
    await page.locator('input[type=file]').setInputFiles({name:'教学验收.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')})
    await page.getByText(/已在本地保存并选中 1 张截图/).waitFor()
    assert.equal(posts.length,0)
    await page.reload()
    const selected=page.getByRole('checkbox',{name:'选定资料 教学验收.png'})
    await selected.check()
    await page.getByLabel('你想完成什么？有什么要求？').fill('为这次作业分别安排整理实验结果和撰写总结。')
    const analysis=page.waitForResponse(r=>r.url().endsWith('/api/analyze'),{timeout:150000})
    const proposal=page.waitForResponse(r=>r.url().endsWith('/api/assistant/propose'),{timeout:310000})
    proposal.catch(()=>{})
    await page.getByRole('button',{name:'生成方案',exact:true}).click()
    const a=await analysis;const ab=await a.json()
    console.log('个人截图提取',a.status(),'字段',ab.fields?.length,ab.code||'')
    assert(a.ok() && ab.fields.length>0)
    const p=await proposal;const pb=await p.json()
    console.log('个人规划',p.status(),pb.code||'',pb.status||'',Object.keys(pb))
    assert(p.ok())
    assert.deepEqual(errors,[])
    console.log('通过：教学四步、返回和重播、移动布局、演示禁上传和粘贴拖放；个人保存、刷新后保留、真实提取和规划。')
  } finally {await browser.close()}
})().catch(e=>{console.error(e.message);process.exitCode=1})
